static const char* BL="/sys/class/backlight/panel0-backlight";
static void blw(const char* f,const char* v){ char p[256]; FILE* h; snprintf(p,sizeof p,"%s/%s",BL,f); if((h=fopen(p,"w"))){ fputs(v,h); fclose(h);} }
static void blank_exit(int s){ (void)s; blw("brightness","0"); blw("bl_power","4"); _exit(0); }

static int g_fd; static uint8_t* g_base; static uint32_t W,Hh,g_pitch; static struct drm_mode_crtc g_set; static uint32_t g_conn;
static void relatch(void){ ioctl(g_fd,DRM_IOCTL_MODE_SETCRTC,&g_set); }
static void px(int x,int y,uint32_t c){ if(x<0||y<0||x>=(int)W||y>=(int)Hh)return; *(uint32_t*)(g_base+y*g_pitch+x*4)=c; }
static void fillr(int x,int y,int w,int h,uint32_t c){ for(int j=0;j<h;j++)for(int i=0;i<w;i++)px(x+i,y+j,c); }
static void ch(int x,int y,int sc,uint32_t c,char ci){ if(ci<0x20||ci>0x7F)ci='?'; const unsigned char* g=FONT[ci-0x20];
  for(int r=0;r<8;r++)for(int b=0;b<8;b++) if(g[r]&(1<<b)) fillr(x+b*sc,y+r*sc,sc,sc,c); }
static void str(int x,int y,int sc,uint32_t c,const char* s){ int cx=x; for(;*s;s++){ if(*s=='\n'){cx=x;y+=9*sc;continue;} ch(cx,y,sc,c,*s); cx+=8*sc; } }

static void rdfile(const char* path,char* out,int n){ out[0]=0; FILE* f=fopen(path,"r"); if(!f)return; if(fgets(out,n,f)){ char* nl=strchr(out,'\n'); if(nl)*nl=0; } fclose(f); }
static int ipv4(char* out,int n){ out[0]=0; struct ifaddrs* ifa; if(getifaddrs(&ifa))return -1;
  for(struct ifaddrs* p=ifa;p;p=p->ifa_next){ if(p->ifa_addr && p->ifa_addr->sa_family==AF_INET && strncmp(p->ifa_name,"wlan",4)==0){
    struct sockaddr_in* s=(struct sockaddr_in*)p->ifa_addr; inet_ntop(AF_INET,&s->sin_addr,out,n); break; } }
  freeifaddrs(ifa); return out[0]?0:-1; }
static int sockok(const char* name){ char p[256]; snprintf(p,sizeof p,"/data/local/ubuntu/opt/hwbridge/%s",name); struct stat st; return stat(p,&st)==0; }

static void draw_frame(void){
  for(uint32_t y=0;y<Hh;y++){ uint32_t* row=(uint32_t*)(g_base+y*g_pitch); uint32_t c=(y<150)?0xFF1E88E5:0xFF0E1116; for(uint32_t x=0;x<W;x++)row[x]=c; }
  char hn[64],ip[64],cap[16],stt[24],up[64];
  rdfile("/data/local/ubuntu/etc/hostname",hn,sizeof hn); if(!hn[0])strcpy(hn,"pixel-node");
  if(ipv4(ip,sizeof ip))strcpy(ip,"kein WLAN");
  rdfile("/sys/class/power_supply/battery/capacity",cap,sizeof cap);
  rdfile("/sys/class/power_supply/battery/status",stt,sizeof stt);
  rdfile("/proc/uptime",up,sizeof up); char* q=strchr(up,' '); if(q)*q=0; long us=atol(up); long uh=us/3600,um=(us%3600)/60;
  uint32_t Wc=0xFFFFFFFF, G=0xFF9AA0A6; int s=3; char line[128];
  str(40,40,4,Wc,"PIXEL BASE NODE");
  int y=200;
  snprintf(line,sizeof line,"Host:  %s",hn); str(40,y,s,Wc,line); y+=40;
  snprintf(line,sizeof line,"IP:    %s",ip); str(40,y,s,Wc,line); y+=40;
  snprintf(line,sizeof line,"Akku:  %s%%  %s",cap[0]?cap:"?",stt[0]?stt:""); str(40,y,s,Wc,line); y+=40;
  snprintf(line,sizeof line,"Uptime: %ldh %ldm",uh,um); str(40,y,s,Wc,line); y+=60;
  str(40,y,s,G,"Beschleuniger:"); y+=40;
  struct { const char* n; const char* sock; } acc[]={{"TPU","tpu.sock"},{"GPU","gpu.sock"},{"GPU-ZC","gpuzc.sock"},{"DSP","gxp.sock"}};
  for(int i=0;i<4;i++){ int ok=sockok(acc[i].sock); uint32_t dot=ok?0xFF34A853:0xFFEA4335;
    fillr(48,y+4,20,20,dot); snprintf(line,sizeof line,"   %-7s %s",acc[i].n,ok?"bereit":"---"); str(72,y,s,Wc,line); y+=36; }
}

int main(int argc,char**argv){
  int secs=argc>1?atoi(argv[1]):60;
  signal(SIGTERM,blank_exit); signal(SIGINT,blank_exit);
  g_fd=open("/dev/dri/card0",O_RDWR|O_CLOEXEC); if(g_fd<0){perror("card0");return 1;}
  ioctl(g_fd,DRM_IOCTL_SET_MASTER,0);
  struct drm_mode_card_res res; memset(&res,0,sizeof res);
  if(ioctl(g_fd,DRM_IOCTL_MODE_GETRESOURCES,&res)<0)return 1;
  uint32_t conns[32],crtcs[32],encs[32],fbs[32];
  res.connector_id_ptr=(uint64_t)(uintptr_t)conns; res.count_connectors=res.count_connectors>32?32:res.count_connectors;
  res.crtc_id_ptr=(uint64_t)(uintptr_t)crtcs; res.count_crtcs=res.count_crtcs>32?32:res.count_crtcs;
  res.encoder_id_ptr=(uint64_t)(uintptr_t)encs; res.count_encoders=res.count_encoders>32?32:res.count_encoders;
  res.fb_id_ptr=(uint64_t)(uintptr_t)fbs; res.count_fbs=res.count_fbs>32?32:res.count_fbs;
  if(ioctl(g_fd,DRM_IOCTL_MODE_GETRESOURCES,&res)<0)return 1;
  struct drm_mode_modeinfo mode; int have=0; uint32_t enc=0;
  for(uint32_t i=0;i<res.count_connectors&&!have;i++){ struct drm_mode_get_connector c; memset(&c,0,sizeof c); c.connector_id=conns[i];
    if(ioctl(g_fd,DRM_IOCTL_MODE_GETCONNECTOR,&c)<0)continue; if(!c.count_modes||c.connection!=1)continue;
    struct drm_mode_modeinfo ms[64]; uint32_t me[16],mp[64]; uint64_t mpv[64];
    c.modes_ptr=(uint64_t)(uintptr_t)ms; c.count_modes=c.count_modes>64?64:c.count_modes;
    c.encoders_ptr=(uint64_t)(uintptr_t)me; c.count_encoders=c.count_encoders>16?16:c.count_encoders;
    c.props_ptr=(uint64_t)(uintptr_t)mp; c.prop_values_ptr=(uint64_t)(uintptr_t)mpv; c.count_props=c.count_props>64?64:c.count_props;
    if(ioctl(g_fd,DRM_IOCTL_MODE_GETCONNECTOR,&c)<0)continue; if(!c.count_modes)continue;
    mode=ms[0]; g_conn=c.connector_id; enc=c.encoder_id; have=1; }
  if(!have){fprintf(stderr,"kein Panel\n");return 1;}
  uint32_t crtc=0; if(enc){ struct drm_mode_get_encoder e; memset(&e,0,sizeof e); e.encoder_id=enc; if(ioctl(g_fd,DRM_IOCTL_MODE_GETENCODER,&e)==0&&e.crtc_id)crtc=e.crtc_id; }
  if(!crtc&&res.count_crtcs)crtc=crtcs[0];
  struct drm_mode_create_dumb creq; memset(&creq,0,sizeof creq); creq.width=mode.hdisplay; creq.height=mode.vdisplay; creq.bpp=32;
  ioctl(g_fd,DRM_IOCTL_MODE_CREATE_DUMB,&creq);
  struct drm_mode_fb_cmd fb; memset(&fb,0,sizeof fb); fb.width=creq.width; fb.height=creq.height; fb.pitch=creq.pitch; fb.bpp=32; fb.depth=24; fb.handle=creq.handle;
  ioctl(g_fd,DRM_IOCTL_MODE_ADDFB,&fb);
  struct drm_mode_map_dumb mreq; memset(&mreq,0,sizeof mreq); mreq.handle=creq.handle; ioctl(g_fd,DRM_IOCTL_MODE_MAP_DUMB,&mreq);
  g_base=mmap(0,creq.size,PROT_READ|PROT_WRITE,MAP_SHARED,g_fd,mreq.offset); if(g_base==MAP_FAILED)return 1;
  W=creq.width; Hh=creq.height; g_pitch=creq.pitch;
  memset(&g_set,0,sizeof g_set); g_set.crtc_id=crtc; g_set.fb_id=fb.fb_id; g_set.set_connectors_ptr=(uint64_t)(uintptr_t)&g_conn; g_set.count_connectors=1; g_set.mode=mode; g_set.mode_valid=1;
  draw_frame();   /* erstes Bild VOR dem Modeset (sonst latcht ein schwarzer Puffer) */
  int sc=ioctl(g_fd,DRM_IOCTL_MODE_SETCRTC,&g_set);
  fprintf(stderr,"[dashd] Panel %ux%u crtc=%u conn=%u SETCRTC=%d\n",W,Hh,g_set.crtc_id,g_conn,sc);
  blw("bl_power","0"); blw("brightness","3000");
  struct timespec t0; clock_gettime(CLOCK_MONOTONIC,&t0);
  for(;;){
    struct timespec now; clock_gettime(CLOCK_MONOTONIC,&now);
    if(secs>0 && now.tv_sec-t0.tv_sec>=secs) break;
    draw_frame(); relatch();
    sleep(2);
  }
  blank_exit(0); return 0;
}
